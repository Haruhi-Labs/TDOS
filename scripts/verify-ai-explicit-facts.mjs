import assert from "node:assert/strict";
import { resolveAiParams } from "../shared/game/ai/params/index.js";
import { contactHpRatio, contactCombatValue, enemyThreatAround, shipThreatSnapshot, friendlyPowerAround } from "../shared/game/ai/policy/evaluation.js";
import { safeRoutePadding, zoneCenter } from "../shared/game/ai/policy/geometry.js";
import { planMode } from "../shared/game/ai/policy/mode.js";
import { freezePlainData } from "../shared/data/plain-data.js";
import { POLICY_PROGRAM_INPUTS } from "../shared/game/ai/policy/policy-inputs.js";
const params = resolveAiParams();
const contact = freezePlainData({ id: 2, kind: "ship", characterId: "kyon", slotKey: "main", x: 100, y: 100, hp: 50, maxHp: 100, confidence: 1, visible: true });
assert.equal(contactHpRatio(params.value, contact), 0.5);
assert.ok(contactCombatValue(params.value, contact) > 0);
const ship = freezePlainData({ id: 1, kind: "ship", key: "main", alive: true, x: 90, y: 100, hp: 100, maxHp: 100, energy: 50, maxEnergy: 100, stats: { range: 200, damage: 10, fireRate: 1 } });
const facts = freezePlainData({ valueParams: params.value, contacts: [contact], ships: [ship], wingmen: [], scouts: [] });
const before = JSON.stringify(facts);
const first = shipThreatSnapshot(facts, ship);
assert.ok(first.pressure > 0);
assert.ok(enemyThreatAround(facts, 90, 100) > 0);
assert.ok(friendlyPowerAround(facts, 90, 100) > 0);
assert.deepEqual(shipThreatSnapshot(facts, ship), first);
assert.equal(JSON.stringify(facts), before, "估值查询不能改写事实");
assert.equal(safeRoutePadding(1440), 115.2);
assert.deepEqual(zoneCenter([{ id: 5, x: 20, y: 40, width: 10, height: 20 }], 5), { zoneId: 5, x: 25, y: 50 });
let draws = 0;
const state = freezePlainData({ modeParams: params.mode, currentMode: "press", currentTimer: 10 });
const result = planMode(state, { edgePressure: 1, barrierTactics: {} }, (min, max) => { draws++; return (min + max) / 2; });
assert.equal(result.mode, "recover");
assert.equal(state.currentMode, "press", "规划只返回候选，不提交模式");
assert.equal(draws, 1, "强制模式保持原来的随机消费次数");
assert.deepEqual(POLICY_PROGRAM_INPUTS.planEnergyThrottleCap, ["energyThrottleGearCap"]);
assert.ok(!POLICY_PROGRAM_INPUTS.contactHpRatio, "纯算法没有策略查询上下文");
console.log("AI 显式事实通过：无策略实例的估值、几何、模式候选、输入隔离与随机次数");
