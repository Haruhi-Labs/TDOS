import assert from "node:assert/strict";
import { MatchSimulation } from "../shared/game-core.js";
import { prepareBunnyCompanions, convertBunnyCompanion, cleanupBunnyCompanions } from "../shared/game/bunny-companion-runtime.js";
import { initializeBunnyBattle, resolveBunnyStages, advanceBunnyRules, cleanupBunnySources } from "../shared/game/bunny-haruhi-runtime.js";

const sim = new MatchSimulation({ seed: 188, teamLoadouts: { A: { main: "kyon", sub1: "bunny_haruhi", sub2: "yuki" } } });
const team = sim.teamA;
team.split(1);
const owner = team.ships.sub1;
for (let cast = 0; cast < 4; cast += 1) {
  team.cooldowns.sub1 = 0;
  owner.restoreHull(owner.maxHp);
  assert.equal(team.castSubSkill("sub1"), true);
}
const companion = team.extraShips[0];
assert.equal(owner.bunnyHaruhi.companionId, companion.id);
assert.equal(companion.bunnyCompanion.ownerShipId, owner.id);
assert.throws(() => { owner.bunnyHaruhi.companionId = null; }, TypeError);
assert.throws(() => { owner.bunnyHaruhi = {}; }, TypeError);
assert.throws(() => { companion.bunnyCompanion.convertedUntil = 100; }, TypeError);
assert.throws(() => { companion.bunnyCompanion.followOffset.forward = 999; }, TypeError);
assert.throws(() => { companion.bunnyCompanion = {}; }, TypeError);
const beforeDuplicate = JSON.stringify(sim.serializeState());
const nextId = sim.entityIds.value;
assert.equal(team.spawnBunnyCompanion(owner), null);
assert.equal(sim.entityIds.value, nextId, "重复生成不得再消费实体编号");
assert.equal(JSON.stringify(sim.serializeState()), beforeDuplicate);

sim.elapsed = 20; sim.tick = 600;
prepareBunnyCompanions(sim);
assert.ok(owner.bunnyReliable && companion.bunnyReliable);
assert.notEqual(owner.bunnyReliable, companion.bunnyReliable);
assert.throws(() => { owner.bunnyReliable.suppressed = true; }, TypeError);
assert.throws(() => { owner.bunnyReliable = null; }, TypeError);
owner.clearActiveSkillBuffs();
assert.equal(owner.bunnyReliable.suppressed, false, "本帧保护属于增益所有者");
sim.tick += 1;
owner.clearActiveSkillBuffs();
assert.equal(owner.bunnyReliable.suppressed, true);
assert.equal(companion.bunnyReliable.suppressed, false, "接收者的净化不得修改另一个接收者的状态");
assert.equal(convertBunnyCompanion(companion, sim.teamB, sim.zoneById(5)), true);
assert.equal(owner.bunnyReliable, undefined);
assert.equal(companion.bunnyReliable, undefined);
assert.equal(companion.team, sim.teamB);
assert.equal(team.extraShips.includes(companion), false);
assert.equal(sim.teamB.extraShips.filter((ship) => ship === companion).length, 1);
sim.elapsed = 25;
prepareBunnyCompanions(sim);
assert.equal(companion.team, team);
assert.equal(companion.bunnyCompanion.convertedUntil, 0);
owner.retireWithoutLoss();
cleanupBunnyCompanions(sim);
assert.equal(companion.alive, false);
assert.equal(companion.bunnyCompanion.nextReliableAt, null);
assert.equal(owner.bunnyHaruhi.companionId, companion.id, "死亡仍保留一次性生成历史");
assert.equal(owner.bunnyHaruhi.companionSpawned, true);

const stage = new MatchSimulation({ seed: 133, teamLoadouts: { B: { main: "bunny_haruhi", sub1: "koizumi", sub2: "kyon" } } });
const target = stage.teamA.ships.main;
const source = stage.teamB.ships.main;
target.displaceTo(source.x, source.y);
resolveBunnyStages(stage);
assert.equal(target.bunnyStageExposure.inside, true);
assert.throws(() => { target.bunnyStageExposure.inside = false; }, TypeError);
assert.throws(() => { target.bunnyStageExposure = {}; }, TypeError);
const sampled = target.bunnyStageExposure;
target.serialize(); target.serialize();
assert.equal(target.bunnyStageExposure, sampled, "投影不得替换成员关系或推进阶段");
target.displaceTo(50, 50);
resolveBunnyStages(stage);
assert.equal(target.bunnyStageExposure.inside, false);
assert.equal(sampled.inside, true, "后续状态提交不修改已读取的历史视图");

const sampledStage = stage.teamB.bunnyStage;
assert.throws(() => { stage.teamB.bunnyStage = null; }, TypeError);
assert.throws(() => { sampledStage.radius = 999; }, TypeError);
assert.throws(() => { stage.bunnyHaruhiActive = false; }, TypeError);
assert.equal(Object.hasOwn(stage, "bunnySustainAt"), false, "结算游标不得泄露到对局公共状态");
source.displaceTo(source.x + 10, source.y);
const projected = stage.serializeState();
projected.teams.B.bunnyStage.x = -999;
assert.equal(stage.teamB.bunnyStage, sampledStage, "序列化只读取已提交的舞台样本");
resolveBunnyStages(stage);
assert.equal(stage.teamB.bunnyStage.x, sampledStage.x + 10);
assert.notEqual(stage.teamB.bunnyStage, sampledStage, "新阶段提交不得修改旧样本");

target.displaceTo(source.x, source.y);
target.drainHull(target.hp - 300);
resolveBunnyStages(stage);
stage.elapsed = 10;
advanceBunnyRules(stage);
const firstHeal = target.hp;
assert.ok(firstHeal > 300, "入迷阶段仍结算首次治疗");
initializeBunnyBattle(stage);
advanceBunnyRules(stage);
assert.equal(target.hp, firstHeal, "重复初始化与阶段调用不得重置结算游标或重复治疗");
stage.elapsed = 11;
advanceBunnyRules(stage);
assert.equal(target.hp, firstHeal + target.maxHp * 0.004, "下一秒持续治疗只消费新的时间区间");
const advanced = target.hp;
stage.serializeState(); resolveBunnyStages(stage); advanceBunnyRules(stage);
assert.equal(target.hp, advanced, "重复投影与成员采样不得额外消费持续资源");
source.retireWithoutLoss();
cleanupBunnySources(stage);
assert.equal(stage.teamB.bunnyStage, null);
assert.equal(target.bunnyStageExposure.inside, false);
assert.ok(sampledStage.radius > 0, "来源死亡清理不得改写历史样本");

const independent = new MatchSimulation({ seed: 134, teamLoadouts: { B: { main: "bunny_haruhi", sub1: "koizumi", sub2: "kyon" } } });
const independentTarget = independent.teamA.ships.main;
independentTarget.displaceTo(independent.teamB.ships.main.x, independent.teamB.ships.main.y);
independentTarget.drainHull(independentTarget.hp - 300);
resolveBunnyStages(independent);
independent.elapsed = 10;
advanceBunnyRules(independent);
assert.equal(independentTarget.hp, firstHeal, "不同对局不得共享持续结算游标");

const ordinary = new MatchSimulation({ seed: 135 });
assert.equal(initializeBunnyBattle(ordinary), false);
advanceBunnyRules(ordinary); resolveBunnyStages(ordinary); cleanupBunnySources(ordinary);
assert.equal(Object.hasOwn(ordinary, "bunnyHaruhiActive"), false);
assert.equal(Object.hasOwn(ordinary.teamA, "bunnyStage"), false, "无舞台阵容不增加角色字段");
console.log("兔女郎所有权校验通过：关系一次提交、冻结状态、独立受益资格、策反归还、死亡、舞台采样与持续结算所有权。");
