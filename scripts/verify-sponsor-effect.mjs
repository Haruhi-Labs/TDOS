import { ScenarioSimulation, sampleScenarioTime } from "./core-tests/scenario-simulation.mjs";
import { setScenarioField } from './core-tests/ship-fixture.mjs';
import assert from "node:assert/strict";
import { SponsorEffect } from "../shared/game/characters/tsuruya/sponsor-effect.js";


let now = 10;
let tick = 30;
const calls = [];
const effect = new SponsorEffect({ now: () => now, tick: () => tick, activated: () => calls.push("激活"), restoreHullFraction: (fraction, dt) => calls.push([fraction, dt]) });
assert.equal(effect.active(), false);
effect.activate(8);
assert.equal(effect.expiresAt, 18);
assert.equal(effect.cooldownStep(0.1), 0.2);
effect.regenerate(0.1);
assert.deepEqual(calls, ["激活", [0.01, 0.1]]);
assert.equal(effect.clear(), false, "本帧净化不能抹掉刚激活的赞助");
assert.equal(effect.active(), true);
tick += 1;
assert.equal(effect.clear(), true);
assert.equal(effect.cooldownStep(0.1), 0.1);
effect.regenerate(1);
assert.equal(calls.length, 2, "被净化后不继续恢复");
effect.activate(8);
now = 18;
assert.equal(effect.active(), false, "到期点不多结算一帧");
assert.equal(effect.expiresAt, 18, "查询到期不负责清理状态");
assert.equal(effect.clear({ preserveCurrentTick: false }), false);
assert.equal(effect.expiresAt, 0);
assert.throws(() => { effect.expiresAt = Infinity; }, TypeError);

const match = new ScenarioSimulation({ seed: 534, teamLoadouts: { A: { main: "tsuruya", sub1: "kyon", sub2: "yuki" } } });
const team = match.teamA;
setScenarioField(team.ships.main, 'hp', team.ships.main.hp - (10));
assert.equal(team.castFlagshipSkill(), true);
assert.throws(() => { team.effects = {}; }, TypeError, "不能替换效果投影来绕过所有者");
assert.throws(() => { team.effects.sponsorUntil = 0; }, TypeError, "外部不能绕过赞助净化保护");
const hp = team.ships.main.hp;
team.sponsorRegeneration(0.1);
assert.equal(team.ships.main.hp, hp + team.ships.main.maxHp * 0.01 * 0.1);
assert.equal(team.clearActiveTeamSkillBuffs(), false);
sampleScenarioTime(match, { tick: match.tick + (1) });
assert.equal(team.clearActiveTeamSkillBuffs(), true);
assert.equal(team.effects.sponsorUntil, 0);
console.log("赞助生命周期校验通过：寿命、回血、冷却与同帧净化保护由同一私有状态驱动。");
