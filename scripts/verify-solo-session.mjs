import assert from "node:assert/strict";
import { createSoloSession } from "../src/solo/session.js";
import { TICK_DT } from "../shared/game/constants.js";
import { matchActions } from "../shared/protocol/match-actions.js";

const ticks = (state) => Math.round(state.elapsed / TICK_DT);
const session = createSoloSession();
const initial = session.reset({ mode: "pvp", seed: 431 }, 1000);
assert.equal(session.simulation, undefined, "页面不得取得权威模拟");
assert.equal(session.clock, undefined, "页面不得修改逻辑时钟");
assert.throws(() => { initial.teams.A.ships.main.hp = -1; }, TypeError);
const initialThrottle = initial.teams.A.ships.main.throttle;
assert.equal(session.applyAction("A", matchActions.setThrottle({ shipKey: "main", throttle: 1.4 })), true);
assert.equal(session.shipControl("main").throttle, 1.4, "帧间控制查询必须立即读到已提交动作");
assert.equal(initial.teams.A.ships.main.throttle, initialThrottle, "旧快照不应随动作变化");
const route = matchActions.setRoute({ shipKey: "main", endX: 800, endY: 900, throttle: session.shipControl("main").throttle });
assert.equal(session.applyAction("A", route), true);
const between = session.advance(1005);
assert.equal(ticks(between.state), 0);
assert.equal(between.state.teams.A.ships.main.throttle, 1.4, "不足一个固定步也应刷新离散输入");
assert.throws(() => { session.shipControl("main").canControl = false; }, TypeError);
const stepped = session.advance(1040);
assert.equal(ticks(stepped.state), 1);
const hp = stepped.state.teams.A.ships.main.hp;
if (stepped.renderState !== stepped.state) stepped.renderState.teams.A.ships.main.hp = -999;
assert.equal(session.advance(1041).state.teams.A.ships.main.hp, hp, "显示插值不得写回权威或下一帧");
assert.equal(ticks(session.advance(2000, { paused: true }).state), 1, "暂停期间不得推进或积累追帧");
assert.equal(ticks(session.advance(2010).state), 1);
assert.equal(ticks(session.advance(2300).state), 7, "卡顿追帧上限保持六步");
assert.equal(ticks(session.advance(2301).state), 7, "丢弃追帧积压不得在下一帧继续爆发");
const restarted = session.reset({ mode: "pvp", seed: 431 }, 3000);
assert.deepEqual(restarted, initial, "重开不得继承上一局时钟、插值帧或指令");
assert.equal(ticks(session.advance(3001).state), 0);
session.reset({ mode: "ai", seed: 431, tutorialMode: true }, 4000);
const beforeStage = session.advance(4001).state;
session.setTutorialStage("free");
assert.equal(ticks(session.advance(4040).state), ticks(beforeStage) + 1);
console.log("单人会话校验通过：权威隔离、即时输入、显示不回写、暂停、追帧与重开保持契约。");
