import assert from "node:assert/strict";
import { MatchTelemetry } from "../shared/game/runtime/match-telemetry.js";
import { MatchSimulation } from "../shared/game-core.js";

const telemetry = new MatchTelemetry();
const initial = telemetry.serialize();
assert.equal(telemetry.teams, undefined, "不公开可写计数表");
telemetry.recordAction("A", "set_route");
telemetry.recordAttack("A", "beam", 2);
telemetry.recordAttack("A", "projectile");
telemetry.recordAttack("A", "projectile_hit");
telemetry.recordDamage("A", "B", 1.125, "skill");
telemetry.recordDamage(null, "B", 0.25, "不存在的类型");
telemetry.recordShipLoss("B");
const snapshot = telemetry.serialize();
assert.deepEqual(snapshot.teams.A.actions, { set_route: 1 });
assert.deepEqual(snapshot.teams.A.attacks, { projectileFired: 1, projectileHits: 1, beamFired: 1, beamHits: 2 });
assert.equal(snapshot.teams.A.damageDealt.skill, 1.13);
assert.equal(snapshot.teams.B.damageTaken.skill, 1.13);
assert.equal(snapshot.teams.B.damageTaken.unknown, 0.25);
assert.equal(snapshot.teams.B.shipsLost, 1);
assert.deepEqual(telemetry.serialize(), snapshot, "读取不推进或重置统计");
assert.deepEqual(initial.teams.A.actions, {}, "已发布结果不跟随事件更新");

snapshot.teams.A.actions.set_route = 999;
snapshot.teams.A.attacks.beamHits = 999;
snapshot.teams.B.damageTaken.skill = 999;
snapshot.teams.B.shipsLost = 999;
const isolated = telemetry.serialize();
assert.equal(isolated.teams.A.actions.set_route, 1);
assert.equal(isolated.teams.A.attacks.beamHits, 2);
assert.equal(isolated.teams.B.damageTaken.skill, 1.13);
assert.equal(isolated.teams.B.shipsLost, 1);
telemetry.recordDamage("A", "B", -5, "skill");
telemetry.recordAction("C", "set_route");
telemetry.recordAttack("C", "beam", 9);
telemetry.recordShipLoss("C");
assert.deepEqual(telemetry.serialize(), isolated, "非法席位和负伤害不影响既有记录");
assert.deepEqual(new MatchTelemetry().serialize(), initial, "统计实例之间不共享存储");

const match = new MatchSimulation({ seed: 20 });
assert.equal(match.telemetry, undefined, "Match 不再挂载原始统计存储");
match.recordDamage(match.teamA.ships.main, match.teamB.ships.main, 3, "skill");
match.recordAction("A", "cast_beam");
match.recordAttack("A", "beam", 1);
match.recordShipLoss("B");
const summary = match.statisticsSummary();
assert.equal(summary.telemetry.teams.A.damageDealt.skill, 3);
assert.equal(summary.telemetry.teams.A.actions.cast_beam, 1);
assert.equal(summary.telemetry.teams.A.attacks.beamHits, 1);
assert.equal(summary.telemetry.teams.B.shipsLost, 1);
summary.telemetry.teams.A.damageDealt.skill = 500;
assert.equal(match.statisticsSummary().telemetry.teams.A.damageDealt.skill, 3);
console.log("统计所有权校验通过：事件入口、私有计数、结算副本隔离和原有取整语义。");
