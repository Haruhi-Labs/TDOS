import assert from "node:assert/strict";
import { MatchSimulation } from "../shared/game-core.js";

const sim = new MatchSimulation({ seed: 228 });
const target = sim.teamA.ships.main;
const claw = { sourceSeat: "B", triggerHits: 3, markDuration: 4, burstDamage: 20, color: "#fff" };
const initial = target.clawMarks;
assert.throws(() => { target.clawMarks = {}; }, TypeError);
assert.throws(() => { target.clawMarks.stacks = 999; }, TypeError);
assert.equal(target.registerClawHit(claw, sim), false);
const first = target.activeClawMarks();
assert.equal(first.stacks, 1);
assert.equal(target.activeClawMarks(), first, "未变化的状态查询可复用只读结果");
assert.equal(initial.stacks, 0, "命中不能改写历史状态");
assert.throws(() => { first.required = 1; }, TypeError);
target.registerClawHit(claw, sim);
const takeDamage = target.takeDamage.bind(target);
let damageCalls = 0;
target.takeDamage = (...args) => {
  damageCalls += 1;
  assert.equal(target.clawMarks.stacks, 0, "爆发承伤前先清空层数");
  assert.equal(target.clawMarks.expiresAt, 0);
  return takeDamage(...args);
};
assert.equal(target.registerClawHit(claw, sim), true);
assert.equal(damageCalls, 1);
assert.equal(first.stacks, 1);
target.registerClawHit(claw, sim);
target.registerClawHit({ ...claw, sourceSeat: "A" }, sim);
assert.equal(target.clawMarks.stacks, 1, "来源切换不得累加另一来源的层数");
assert.equal(target.clawMarks.sourceSeat, "A");
const pending = target.clawMarks;
sim.elapsed = 4;
assert.equal(target.activeClawMarks().stacks, 0);
assert.throws(() => { target.activeClawMarks().stacks = 2; }, TypeError);
target.serialize();
assert.equal(target.clawMarks, pending, "到期查询与投影不得提交清理");
target.expireClawMarks();
assert.equal(target.clawMarks.stacks, 0);
assert.equal(target.clawMarks.sourceSeat, null);
assert.equal(pending.stacks, 1);
target.registerClawHit(claw, sim);
target.clearNegativeEffects();
assert.equal(target.clawMarks.stacks, 0, "负面净化通过抓痕所有者提交");
assert.equal(target.clawMarks.required, 3, "净化保留原有的命中阈值与颜色语义");
assert.equal(target.clawMarks.color, "#fff");
target.retireWithoutLoss();
const dead = target.clawMarks;
assert.equal(target.registerClawHit(claw, sim), false);
assert.equal(target.clawMarks, dead, "死亡拒绝不得创建新状态");
console.log("抓痕所有权校验通过：私有状态、历史隔离、查询纯度、来源切换、爆发顺序与净化。");
